-- 2. TABELAS SECUNDÁRIAS (LOOKUP / ENUM)
--============================================

CREATE TABLE TiposUsuario (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR2(20 CHAR) NOT NULL
);

CREATE TABLE StatusConta (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_status VARCHAR2(50 CHAR) NOT NULL
);

CREATE TABLE TiposInvestimento (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(150 CHAR) NOT NULL,
    rentabilidade_mes NUMBER(10,6),
    carencia_dias NUMBER(10) NOT NULL,
    valorMinimo NUMBER(10,2) DEFAULT 0.00 NOT NULL
);

CREATE TABLE TiposMovimento (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_movimento VARCHAR2(50 CHAR) NOT NULL
);

CREATE TABLE StatusEmprestimo (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR2(20 CHAR) NOT NULL
);

CREATE TABLE StatusParcelasEmprestimo (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR2(50 CHAR) NOT NULL
);


--============================================
-- 3. TABELAS PRINCIPAIS (ENTIDADES)
--============================================

CREATE TABLE Usuarios (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CPF VARCHAR2(11 CHAR) NOT NULL UNIQUE,
    senha VARCHAR2(100 CHAR) NOT NULL, 
    email VARCHAR2(150 CHAR) NOT NULL UNIQUE,
    id_tipo_usuario NUMBER(10) NOT NULL
);

CREATE TABLE Enderecos (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    logradouro VARCHAR2(255 CHAR) NOT NULL,
    numero NUMBER(10),
    complemento VARCHAR2(255 CHAR),
    bairro VARCHAR2(150 CHAR) NOT NULL,
    cidade VARCHAR2(150 CHAR) NOT NULL,
    estado VARCHAR2(2 CHAR) NOT NULL,
    cep VARCHAR2(9 CHAR) NOT NULL
);

CREATE TABLE Telefones (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_pais NUMBER(10) NOT NULL,
    cod_area NUMBER(10) NOT NULL,
    numero NUMBER(10) NOT NULL
);

CREATE TABLE Gerentes (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(150 CHAR) NOT NULL,
    data_nascimento DATE NOT NULL,
    id_usuario NUMBER(10) NOT NULL
);

CREATE TABLE Clientes (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(150 CHAR) NOT NULL,
    data_nascimento DATE NOT NULL,
    data_cadastro DATE NOT NULL,
    foto_url VARCHAR2(500 CHAR),
    id_usuario NUMBER(10) NOT NULL,
    id_endereco NUMBER(10) NOT NULL,
    id_telefone NUMBER(10) NOT NULL
);

CREATE TABLE Contas (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_conta VARCHAR2(10 CHAR) NOT NULL,
    saldo NUMBER(10,2) DEFAULT 0.00 NOT NULL,
    data_abertura DATE NOT NULL,
    id_status_conta NUMBER(10) NOT NULL,
    id_cliente NUMBER(10) NOT NULL UNIQUE
);

CREATE TABLE AplicacoesInvestimentos (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor_aplicado NUMBER(10,2) NOT NULL,
    data_aplicacao DATE NOT NULL,
    id_conta NUMBER(10) NOT NULL,
    id_tipo_investimento NUMBER(10) NOT NULL,
    status VARCHAR2(20 CHAR) DEFAULT 'ATIVA'
);

CREATE TABLE Movimentacoes (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor NUMBER(10,2) NOT NULL,
    data_movimento DATE NOT NULL,
    id_conta NUMBER(10) NOT NULL,
    id_conta_destino NUMBER(10),
    id_tipo_movimento NUMBER(10) NOT NULL
);

CREATE TABLE Emprestimos (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor_total NUMBER(10,2) NOT NULL,
    valor_entrada NUMBER(10,2) DEFAULT 0.00 NOT NULL,
    data_contratacao DATE NOT NULL,
    numeros_parcelas NUMBER(10) NOT NULL,
    taxa_juros FLOAT NOT NULL,
    id_conta NUMBER(10) NOT NULL,
    id_status_emprestimo NUMBER(10) NOT NULL
);

CREATE TABLE ParcelasEmprestimos (
    id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_parcela NUMBER(10) NOT NULL,
    valor_parcela NUMBER(10,2) NOT NULL,
    data_vencimento DATE NOT NULL,
    valor_pago NUMBER(10,2),
    data_pagamento DATE,
    id_emprestimo NUMBER(10) NOT NULL,
    id_status_parcela NUMBER(10) NOT NULL,
    valor_amortizacao NUMBER(10,2),
    valor_juros NUMBER(10,2),
    saldo_devedor_apos_pagamento NUMBER(10,2)
); 

CREATE TABLE RecuperacaoSenha (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario NUMBER NOT NULL,
    token VARCHAR2(100 CHAR) NOT NULL,
    data_expiracao DATE NOT NULL,
    usado CHAR(1 CHAR) DEFAULT 'N'
);


